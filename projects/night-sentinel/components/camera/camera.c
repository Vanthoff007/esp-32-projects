#include "esp_log.h"
#include "board_pins.h"
#include "camera.h"

// Sources:
// - camera_config_t layout + fb_get/fb_return pattern: usage example at the top of
//   managed_components/espressif__esp32-camera/driver/include/esp_camera.h
// - XCLK 20 MHz, LEDC timer/channel 0, OV3660 vflip: initCamera() in DFRobot
//   DFR1154_Examples "5.3 CameraWebServer/source code/5_3/5_3.ino"
// - RGB565 / QVGA / 2 buffers in PSRAM / GRAB_LATEST: Day 2 plan in docs/next_steps.md

static const char *TAG = "camera";

esp_err_t ns_cam_init(void)
{
    camera_config_t config = {
        .pin_pwdn     = PIN_CAM_PWDN,
        .pin_reset    = PIN_CAM_RESET,
        .pin_xclk     = PIN_CAM_XCLK,
        .pin_sccb_sda = PIN_CAM_SIOD,
        .pin_sccb_scl = PIN_CAM_SIOC,
        .pin_d0       = PIN_CAM_D0,
        .pin_d1       = PIN_CAM_D1,
        .pin_d2       = PIN_CAM_D2,
        .pin_d3       = PIN_CAM_D3,
        .pin_d4       = PIN_CAM_D4,
        .pin_d5       = PIN_CAM_D5,
        .pin_d6       = PIN_CAM_D6,
        .pin_d7       = PIN_CAM_D7,
        .pin_vsync    = PIN_CAM_VSYNC,
        .pin_href     = PIN_CAM_HREF,
        .pin_pclk     = PIN_CAM_PCLK,

        // XCLK is generated by LEDC timer 0 / channel 0, so nothing else may use them.
        .xclk_freq_hz = 20000000,
        .ledc_timer   = LEDC_TIMER_0,
        .ledc_channel = LEDC_CHANNEL_0,

        // RGB565 QVGA is what the detector takes directly, so no conversion step.
        .pixel_format = PIXFORMAT_RGB565,
        .frame_size   = FRAMESIZE_QVGA,
        .jpeg_quality = 12,   // unused for RGB565, but the driver expects a value

        // Two buffers: one fills while the other is being processed.
        .fb_count     = 2,
        .fb_location  = CAMERA_FB_IN_PSRAM,
        .grab_mode    = CAMERA_GRAB_LATEST,
    };

    esp_err_t err = esp_camera_init(&config);
    if (err != ESP_OK) {
        ESP_LOGE(TAG, "esp_camera_init failed: %s", esp_err_to_name(err));
        return err;
    }

    // The OV3660 is mounted upside down on the DFR1154.
    sensor_t *s = esp_camera_sensor_get();
    s->set_vflip(s, 1);

    // The driver's QVGA RGB565 clocks (SYSCLK 20 MHz, PCLK 10 MHz) give a 180 ms frame
    // (2300 x 783 cycles), i.e. ~5.5 fps. Doubling both gives ~11 fps with 0 NULL frames.
    // Doubling SYSCLK alone starves PCLK and no frames arrive at all.
    // Args: bypass, multiplier, sys_div, root_2x, pre_div, seld5, pclk_manual, pclk_div
    s->set_pll(s, 0, 8, 1, 0, 0, 0, 1, 4);


    ESP_LOGI(TAG, "camera ready (sensor PID 0x%x)", s->id.PID);
    return ESP_OK;
}

camera_fb_t *ns_cam_grab(void)
{
    return esp_camera_fb_get();
}

void ns_cam_release(camera_fb_t *fb)
{
    esp_camera_fb_return(fb);
}
